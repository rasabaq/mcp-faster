// Builds site/js/horse-frames.js from Muybridge's "The Horse in Motion" (1878, public domain).
// Usage: node scripts/horse-frames.ts [path-to-gif]
// With no argument it downloads the GIF from Wikimedia Commons. Needs ffmpeg on the PATH.
import { execFileSync } from "node:child_process";
import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const SOURCE = "https://upload.wikimedia.org/wikipedia/commons/d/dd/Muybridge_race_horse_animated.gif";
const COLS = 120, ROWS = 44, FRAMES = 15;
const OUT = new URL("../site/js/horse-frames.js", import.meta.url);

let gif = process.argv[2];
if (!gif) {
  const res = await fetch(SOURCE, { headers: { "User-Agent": "mcp-faster-site-build" } });
  if (!res.ok) throw new Error("Download failed: " + res.status + " " + res.statusText);
  gif = join(mkdtempSync(join(tmpdir(), "horse-")), "horse.gif");
  writeFileSync(gif, Buffer.from(await res.arrayBuffer()));
}

let raw: Buffer;
try {
  raw = execFileSync("ffmpeg", ["-v", "error", "-i", gif, "-vf", "crop=300:182:0:0,scale=120:44:flags=area,format=gray", "-f", "rawvideo", "-pix_fmt", "gray", "-"], { maxBuffer: 1 << 24 });
} catch (err) {
  if ((err as NodeJS.ErrnoException).code === "ENOENT") {
    console.error("ffmpeg was not found. Install it (for example `brew install ffmpeg`) and run this again.");
    process.exit(1);
  }
  throw err;
}

const size = COLS * ROWS;
if (raw.length !== size * FRAMES) throw new Error("Expected " + FRAMES + " frames of " + size + " bytes, got " + raw.length + " bytes.");

// Dark pixels (the horse) become high digits.
const frames: string[] = [];
for (let f = 0; f < FRAMES; f++) {
  let s = "";
  for (let i = 0; i < size; i++) s += Math.round(Math.min(1, Math.max(0, (168 - raw[f * size + i]!) / 120)) * 15).toString(16);
  frames.push(s);
}

writeFileSync(OUT, `// The horse frames for the ASCII art: ${FRAMES} frames of ${COLS} by ${ROWS} cells, one hex digit per cell (0 is light, f is dark).
// From Eadweard Muybridge, The Horse in Motion, 1878, public domain, via Wikimedia Commons.
// Generated by \`node scripts/horse-frames.ts\`. Do not edit by hand.

export const COLS = ${COLS};
export const ROWS = ${ROWS};
export const FRAMES = ${JSON.stringify(frames)};
`);
console.log("Wrote " + OUT.pathname);
